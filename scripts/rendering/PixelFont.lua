--- 绘制像素风格文本（居中）
---@param vg userdata NanoVG 上下文
---@param text string 文本（大写字母 + 空格 + 冒号）
---@param cx number 中心 X
---@param cy number 中心 Y
---@param pixSize number 每个像素块的尺寸
---@param r number 红色 0-255
---@param g number 绿色 0-255
---@param b number 蓝色 0-255
---@param a number 透明度 0-255
function M.Draw(vg, text, cx, cy, pixSize, r, g, b, a)
    local charW = 5
    local charH = 7
    local gap = 1
    local totalW = #text * (charW + gap) - gap
    local startX = cx - totalW * pixSize * 0.5
    local startY = cy - charH * pixSize * 0.5

    nvgFillColor(vg, nvgRGBA(r, g, b, a))
    for ci = 1, #text do
        local ch = text:sub(ci, ci)
        local glyph = M.GLYPHS[ch]
        if glyph then
            local ox = startX + (ci - 1) * (charW + gap) * pixSize
            for row = 1, charH do
                local rowStr = glyph[row] ---@type string
                if not rowStr then break end
                for col = 1, charW do
                    if rowStr:sub(col, col) == "1" then
                        nvgBeginPath(vg)
                        nvgRect(vg, ox + (col - 1) * pixSize, startY + (row - 1) * pixSize, pixSize, pixSize)
                        nvgFill(vg)
                    end
                end
            end
        end
    end
end

return M
